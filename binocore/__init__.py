"""Общий слой программ семьи BinoDex / BinoEnglish.

Пакет НЕ ставится через pip. Каталог `binocore/` копируется в корень каждой программы
скриптом `sync.py` из репы-эталона BinoCore (вендоринг): программы деплоятся rsync-ом
каталога, venv собирается на ноде, поэтому pip из git добавил бы к деплою сетевую
зависимость, ничего не дав взамен.

Пиннинг при этом естественный: у каждой программы СВОЯ копия, она обновляется тогда, когда
обновляют программу. Это осознанно — иначе один баг в ядре ронял бы все двенадцать программ
разом, включая обе языковые ветки. Расхождение копий ловит `sync.py --check`.

Копия — слепок: править её на месте нельзя, правки вносятся в эталоне и раскладываются заново.

Слои добавляются по одному, снизу вверх:
  images — статичные оверлеи (кэш файла и ресайза);
  db     — пулы PostgreSQL, ретраи, самовосстановление (BaseDatabase) и
           connect_with_retry для стартового чтения конфига до пулов;
  tg     — Premium у юзербота: проверка, отметка в БД, предупреждение в тему ошибок;
  binodex — вход на binodex.app по коду с почты: оба механизма сразу (Privy и собственная
           авторизация binodex), разбор письма, признак живой сессии, крестик модалки поверх
           торговой страницы;
  price   — цена из текста интерфейса в обеих локалях (разбор по позиции разделителей);
  shutdown — штатная остановка: признак, события (async + поток) и прерываемые паузы;
  browser — сессия Playwright: владелец pw/browser/context/вкладок, роли страниц и
           корректное закрытие под таймаутом на каждый шаг.
Дальше по плану: общая процедурная обвязка браузера (подъём контекста, cookies, goto).
"""

