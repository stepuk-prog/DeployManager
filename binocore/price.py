"""Цена из текста интерфейса — единый разбор для всей семьи.

Зачем в ядре. Цену со страницы читают все браузерные программы, и парсер расплодился копиями,
которые уже дважды расходились с реальностью в ОДНУ и ту же сторону — множитель 1000:
  * 24-08-2026, легенда TradingView: запятая била́сь в точку безусловно, и '63,870.00' давало
    63.870 — цена в тысячу раз меньше, молча, прямо в пост;
  * 18-09-2026, шапка binodex Future: запятая резалась безусловно, и ru-формат '2 345,67'
    давал 234567.0 — в сто раз больше, тоже молча и тоже в БД.
Оба раза чинили по месту, а соседние копии оставались с прежней болезнью.

Разбор ПО ПОЗИЦИИ разделителей, а не по символу: и точка, и запятая встречаются в обеих
локалях, поэтому десятичным считается тот разделитель, который правее. Остаётся ровно один
неоднозначный вид — одиночная запятая и РОВНО три цифры за ней ('1,234'): для ru это 1.234, для
en 1234. Его решает язык интерфейса, и гадать не нужно — программа его знает (у русских
программ TV открыт на `ru.`-субдомене, у английских форков на `www.`; см. `lang_from_url`).

Прежняя семейная функция `clear_price` считала одиночный разделитель десятичным ВСЕГДА. Для
форекса это верно ('188,707' в ru-интерфейсе — 188.707), но в английском UI целая цена выше
999 ('2,650') превращалась в 2.65 — та же тысячекратная ошибка, просто ещё не выстрелившая:
у английских форков активы форексные, а TV почти всегда рисует дробную часть.
"""
import re

RU, EN = 'ru', 'en'


def lang_from_url(url: str | None) -> str:
    """Язык интерфейса TradingView по адресу страницы: `ru.tradingview.com` → ru, иначе en.

    Субдомен — то же самое, чем TV переключает язык, так что источник тут первичный: отдельная
    настройка дублировала бы его и могла разъехаться. Пусто/непонятно → ru: это поведение
    прежней `clear_price` (одиночная запятая = десятичный разделитель), то есть при неизвестном
    адресе ничего не меняется."""
    return EN if url and re.match(r'https?://(?!ru\.)[^/]*tradingview\.com', url, re.I) else RU


def clean_price(text: str, lang: str = RU) -> float:
    """Цена из сырого текста → float, В ЛЮБОЙ ЛОКАЛИ интерфейса:
        ru: '63 870,00' — тысячи любым пробелом (обычный/узкий/неразрывный), decimal — запятая;
        en: '63,870.00' — тысячи запятой, decimal — точка;
        обе: '1.15665' — без разделителя тысяч.

    Ничью '1,234' (ru → 1.234, en → 1234) решает `lang`. Прочие одиночные запятые однозначны:
    разделителем тысяч запятая бывает только перед группой из трёх цифр, так что '0,80155' —
    всегда дробь.

    :param text: сырой текст (легенда TV, шапка актива binodex, поле цены)
    :param lang: язык интерфейса ('ru'|'en') — нужен только для ничьей '1,234'
    :raises ValueError: пустая строка или в ней нет числа — вызывающий решает, что это значит
    """
    if not text or not text.strip():
        raise ValueError('Пустая строка цены')
    # Прочь валюту, знаки и ЛЮБЫЕ пробелы — заодно снимается ru-разделитель тысяч.
    s = re.sub(r'[^\d.,]', '', text)
    if ',' in s and '.' in s:
        if s.rfind(',') > s.rfind('.'):
            s = s.replace('.', '').replace(',', '.')   # запятая правее → ru: точка = тысячи
        else:
            s = s.replace(',', '')                     # точка правее → en: запятая = тысячи
    elif ',' in s:
        # Больше одной запятой — заведомо тысячи ('1,234,567'): двух десятичных не бывает.
        # Ровно одна — тысячи только перед группой из трёх цифр, и это ничья: решает язык.
        if s.count(',') > 1 or (lang == EN and re.fullmatch(r'\d{1,3},\d{3}', s)):
            s = s.replace(',', '')
        else:
            s = s.replace(',', '.')
    elif s.count('.') > 1:
        s = s.replace('.', '')                         # '1.234.567' — точка может быть и тысячами
    match = re.search(r'\d+(?:\.\d+)?', s)
    if not match:
        raise ValueError(f"Не найдено число в строке цены: '{text}'")
    return float(match.group())
