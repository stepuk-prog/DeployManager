"""Штатная остановка процесса: признак, события и прерываемые паузы.

ЗАЧЕМ В ЯДРЕ. Механика одинакова у всех программ семьи, а редакций к 20-09-2026 накопилось
три: полная в BinoOptions (`request_shutdown`/`shutdown_event`/`wait_stop`), потоковая в
ForumTrade (`request_stop`/`stopping`) и голый `SHUTDOWN = threading.Event()` внутри
`apps/utils.py` у Screens. Одно и то же разными словами стоило времени при каждом переносе
правок жизненного цикла, а семь программ из двенадцати вообще остались без прерываемой паузы
ожидания кода — то есть с SIGKILL при остановке в неудачный момент.

Глобальное состояние в ядре здесь законно ровно потому, что ядро ВЕНДОРИТСЯ: у каждой
программы своя копия каталога, программа — отдельный процесс, значит события ниже существуют в
единственном экземпляре на процесс. Общего состояния между программами не возникает по
построению. Прецедент рядом: `binocore.db` и `binocore.tg` так же держат свой `_logger`.

ДВА события, а не одно — не дубль состояния, а две стороны одного процесса:
  • `asyncio.Event` — для async-ожиданий (паузы между опционами, бэкофф, окно флуд-контроля);
  • `threading.Event` — для РАБОЧИХ ПОТОКОВ. Ждать `asyncio.Event` из потока нельзя (он не
    потокобезопасен и завязан на loop), а ждать остановку нужно именно оттуда: ожидание кода
    из письма при inline-релогине крутится в `asyncio.to_thread` (`binodex.wait_for_code`).
    Поток про отмену задачи не знает и досиживает своё окно до конца (`CODE_WAIT_SECONDS`=120с),
    а `asyncio.run` в 3.11 join'ит потоки дефолтного пула БЕЗ таймаута — значит сигнал,
    пришедший в это окно, сдвигает НАЧАЛО уборки почти на две минуты. Столько бюджет уборки не
    терпит: systemd приходит с SIGKILL посреди закрытия браузера, Playwright оставляет висячий
    lock в общем кэше ноды, и следующий запуск там браузер не поднимает. Диспетчер при этом
    видит 9/KILL, то есть краш.
Оба события ставит ровно один `request_shutdown`.

`binodex.inline_login` событие отсюда НЕ берёт: он принимает `stop_wait` параметром, и программа
передаёт его явно. Два модуля ядра остаются развязанными, а программа со своим механизмом
остановки может передать собственную паузу.

`asyncio.Event` с Python 3.10 не привязывается к loop'у при СОЗДАНИИ, поэтому объявить событие
на уровне модуля (до старта loop'а) безопасно. А вот при первом ожидании оно защёлкивает текущий
loop — отсюда геттер `shutdown_event()` вместо импорта объекта и пересоздание события в `reset()`.
"""
import asyncio
import threading

_shutdown_requested = False
_shutdown_event = asyncio.Event()
_stop_thread_event = threading.Event()


def request_shutdown() -> None:
    """Пометить штатную остановку. Зовётся из обработчика SIGTERM/SIGINT — в том числе там, где
    обработчик и без того отменяет задачу цикла: отмена гасит async-сторону, а рабочий поток о
    ней не знает, ему нужен флаг.

    Делает две вещи: поднимает признак (по нему сбои ПОСЛЕ сноса драйвера не считаются сбоями и
    не шумят в error-канал) и будит всех, кто ждёт остановку — и async-сторону (`sleep_or_stop`),
    и потоки (`wait_stop`)."""
    global _shutdown_requested
    _shutdown_requested = True
    _shutdown_event.set()
    _stop_thread_event.set()


def shutdown_requested() -> bool:
    """Была ли запрошена штатная остановка."""
    return _shutdown_requested


def shutdown_event() -> asyncio.Event:
    """Событие штатной остановки. Геттер, а не объект в импорте: импортёр иначе защёлкнул бы
    ссылку на момент импорта."""
    return _shutdown_event


def wait_stop(seconds: float) -> bool:
    """Пауза `seconds`, прерываемая остановкой процесса. True — пора уходить, False — вышло время.

    БЛОКИРУЮЩАЯ по построению: её зовут ИЗ ПОТОКА вместо `time.sleep`. Контракт ровно тот,
    которого ждёт `binodex.wait_for_code` от своего `stop_wait` — знак возврата менять нельзя,
    там он читается как «пора уходить»."""
    return _stop_thread_event.wait(seconds)


async def sleep_or_stop(stop_event, seconds: float) -> bool:
    """Прерываемый сон: True — проснулись по сигналу остановки, False — по таймауту.

    Нужен везде, где ждём долго: иначе `sleep(option_time/dgn_time/backoff/FloodWait)` держал бы
    graceful-shutdown минутами, с риском SIGKILL и недозакрытых БД/браузера.

    `stop_event` берётся аргументом, а не изнутри: вызывающие передают сюда и собственные
    события (у части программ ожидание завязано на свой объект). `None` (самый ранний init,
    события ещё нет) — обычный sleep."""
    if stop_event is None:
        await asyncio.sleep(seconds)
        return False
    try:
        await asyncio.wait_for(stop_event.wait(), timeout=seconds)
        return True
    except (asyncio.TimeoutError, TimeoutError):
        return False


def reset() -> None:
    """Сбросить признак и события. Нужен ТЕСТАМ и утилитам, которые поднимают флоу несколько раз
    в одном процессе; боевой код это не зовёт — остановка в процессе бывает один раз.

    `asyncio.Event` именно ПЕРЕСОЗДАЁТСЯ, а не гасится `clear()`: при первом ожидании событие
    защёлкивает текущий loop, и в следующем `asyncio.run` то же самое ожидание упало бы с
    «bound to a different event loop». Поэтому вызывающие и берут событие геттером
    `shutdown_event()`, а не импортом объекта."""
    global _shutdown_requested, _shutdown_event
    _shutdown_requested = False
    _shutdown_event = asyncio.Event()
    _stop_thread_event.clear()
